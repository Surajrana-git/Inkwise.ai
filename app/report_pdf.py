"""Audit report for one draft as a PDF (History page): text, findings with sources, decisions, timeline."""
from __future__ import annotations

import html
import io
from datetime import datetime, timezone

STATUS = {"approved": "Approved", "rejected": "Sent back", "pending": "Waiting for sign-off"}
ACTIONS = {"created": "created the draft", "reviewed": "ran the Inkwise check", "finding_accepted": "accepted a finding",
           "finding_edited": "edited a fix", "finding_rejected": "rejected a finding", "approved": "approved it",
           "changes_requested": "sent it back", "new_version": "saved a new version", "rechecked": "re-checked it"}

CSS = """
* { font-family: sans-serif; }
body { font-size: 9.5pt; color: #1B2A4E; }
h1 { font-size: 17pt; margin: 0 0 2pt 0; }
h2 { font-size: 11pt; margin: 14pt 0 5pt 0; color: #0B5E52; }
.muted { color: #5A6480; font-size: 8.5pt; }
.box { background-color: #F4F6FA; padding: 7pt; }
table { width: 100%; border-collapse: collapse; }
th { text-align: left; font-size: 7.5pt; color: #5A6480; border-bottom: 1px solid #C9D1DE; padding: 3pt; }
td { vertical-align: top; padding: 4pt 3pt; border-bottom: 1px solid #E6EAF0; font-size: 8.5pt; }
.ok { color: #0B5E52; font-weight: bold; } .bad { color: #B42318; font-weight: bold; } .wait { color: #8A4B06; font-weight: bold; }
"""


def _when(stamp: str) -> str:
    try:
        return datetime.fromisoformat(stamp.replace("Z", "+00:00")).strftime("%d %b %Y, %H:%M UTC")
    except Exception:
        return stamp or ""


def build(sub: dict, trail: list[dict], names: dict | None = None) -> bytes:
    """sub: services.list_submissions() item; trail: services.draft_history(); names: username -> full name."""
    import pymupdf

    names = {"inkwise-ai": "Inkwise check", **(names or {})}
    nm = lambda u: html.escape(names.get(u, u or "—"))
    status = STATUS.get(sub["status"], sub["status"])
    cls = {"approved": "ok", "rejected": "bad"}.get(sub["status"], "wait")
    rows = "".join(
        f"<tr><td>{i}</td><td>{html.escape(str(f.get('status', '')).title())}</td>"
        f"<td>{html.escape(str(f.get('category', '')).replace('_', ' '))}"
        f"{' (image)' if f.get('where') == 'image' else ''}</td>"
        f"<td>“{html.escape(f.get('span', ''))}”<br/><span class='muted'>→ {html.escape(f.get('suggested_fix', ''))}</span></td>"
        f"<td><b>{html.escape(f.get('source_id', ''))}</b><br/><span class='muted'>{html.escape(f.get('source_text', '')[:220])}</span></td></tr>"
        for i, f in enumerate(sub.get("findings", []), 1))
    events = "".join(
        f"<tr><td>{html.escape(_when(h.get('at', '')))}</td><td>{nm(h.get('user'))}</td>"
        f"<td>{html.escape(ACTIONS.get(h.get('action', ''), h.get('action', '').replace('_', ' ')))}</td>"
        f"<td class='muted'>{html.escape(h.get('detail', ''))}</td></tr>"
        for h in trail if h.get("kind") == "event")
    decided = (f"{nm(sub.get('decided_by'))} on {html.escape(sub.get('decided_at', ''))} UTC"
               if sub.get("decided_by") else "not yet decided")
    body = f"""
    <p class="muted">INKWISE.AI · AUDIT REPORT · Lumora (fictional demo brand)</p>
    <h1>{html.escape(sub['title'])}</h1>
    <p class="muted">Draft #{html.escape(str(sub['id']))} · version {sub.get('version', 1)} · written by {nm(sub['author'])}
       · sent {html.escape(sub.get('submitted_at', ''))} UTC</p>
    <p>Status: <span class="{cls}">{status}</span> · decided by {decided}</p>
    {f"<p class='box'>Comment: {html.escape(sub['comment'])}</p>" if sub.get('comment') else ''}
    <h2>Text as submitted</h2>
    <p class="box">{html.escape(sub.get('text', ''))}</p>
    <h2>Findings and decisions ({len(sub.get('findings', []))})</h2>
    <table><tr><th>#</th><th>DECISION</th><th>TYPE</th><th>TEXT → FIX</th><th>SOURCE</th></tr>{rows or
        '<tr><td colspan="5">No findings: the draft matched the brand kit.</td></tr>'}</table>
    <h2>Timeline</h2>
    <table><tr><th>WHEN</th><th>WHO</th><th>WHAT</th><th>DETAIL</th></tr>{events}</table>
    <p class="muted" style="margin-top:14pt">Generated by Inkwise.ai on
       {datetime.now(timezone.utc).strftime('%d %b %Y, %H:%M UTC')}. AI findings are suggestions; every change above
       was decided by a person.</p>
    """
    story = pymupdf.Story(html=body, user_css=CSS)
    buf = io.BytesIO()
    writer = pymupdf.DocumentWriter(buf)
    page_rect = pymupdf.paper_rect("a4")
    where = page_rect + (40, 40, -40, -40)
    more = True
    while more:
        dev = writer.begin_page(page_rect)
        more, _ = story.place(where)
        story.draw(dev)
        writer.end_page()
    writer.close()
    return buf.getvalue()
